
"""Evaluate the saved SWYNEX Task 4 churn prediction model.

Run from the project root:

    python -m src.evaluate
"""

import json
from pathlib import Path

import joblib
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
    roc_curve,
)
from sklearn.model_selection import train_test_split

from src.preprocessing import (
    load_dataset,
    prepare_features,
    prepare_target,
)
from src.train import (
    DATA_PATH,
    MODEL_PATH,
    PROJECT_ROOT,
)


RESULTS_DIR = PROJECT_ROOT / "results"
FIGURES_DIR = RESULTS_DIR / "figures"

METRICS_PATH = RESULTS_DIR / "evaluation_metrics.json"
PREDICTIONS_PATH = RESULTS_DIR / "test_predictions.csv"

CONFUSION_FIGURE = FIGURES_DIR / "confusion_matrix.png"
ROC_FIGURE = FIGURES_DIR / "roc_curve.png"


def evaluate_model():
    """Evaluate the saved model on the original test partition."""

    print("=" * 60)
    print("SWYNEX TASK 4 - MODEL EVALUATION")
    print("=" * 60)

    # --------------------------------------------------
    # 1. Load and prepare the dataset
    # --------------------------------------------------

    print("\n[1/6] Loading and preparing test data...")

    df = load_dataset(DATA_PATH)

    X = prepare_features(df)
    y = prepare_target(df)

    _, X_test, _, y_test = train_test_split(
        X,
        y,
        test_size=0.20,
        random_state=42,
        stratify=y,
    )

    print("Test records:", len(X_test))

    assert len(X_test) == 1409
    assert len(y_test) == 1409

    # --------------------------------------------------
    # 2. Load saved model
    # --------------------------------------------------

    print("\n[2/6] Loading saved model...")

    if not MODEL_PATH.is_file():
        raise FileNotFoundError(
            "Saved model not found. "
            "Run 'python -m src.train' first."
        )

    # Only load model artifacts generated by trusted code.
    artifact = joblib.load(MODEL_PATH)

    pipeline = artifact["pipeline"]
    threshold = float(artifact["threshold"])

    if artifact["feature_columns"] != X_test.columns.tolist():
        raise ValueError("Model feature schema does not match.")

    print("Model:", type(
        pipeline.named_steps["classifier"]
    ).__name__)

    print("Classification threshold:", threshold)

    # --------------------------------------------------
    # 3. Generate predictions
    # --------------------------------------------------

    print("\n[3/6] Generating predictions...")

    probabilities = pipeline.predict_proba(
        X_test
    )[:, 1]

    predictions = (
        probabilities >= threshold
    ).astype(int)

    assert len(probabilities) == len(y_test)
    assert np.isfinite(probabilities).all()
    assert np.all(
        (probabilities >= 0)
        & (probabilities <= 1)
    )

    print("PASS: Predictions generated.")

    # --------------------------------------------------
    # 4. Calculate metrics
    # --------------------------------------------------

    print("\n[4/6] Calculating evaluation metrics...")

    metrics = {
        "accuracy": float(
            accuracy_score(y_test, predictions)
        ),
        "precision": float(
            precision_score(
                y_test,
                predictions,
                zero_division=0,
            )
        ),
        "recall": float(
            recall_score(
                y_test,
                predictions,
                zero_division=0,
            )
        ),
        "f1_score": float(
            f1_score(
                y_test,
                predictions,
                zero_division=0,
            )
        ),
        "roc_auc": float(
            roc_auc_score(y_test, probabilities)
        ),
    }

    print("\nFINAL TEST METRICS")
    print("-" * 40)

    for metric_name, score in metrics.items():
        print(f"{metric_name:<15}: {score:.6f}")

    print("\nCLASSIFICATION REPORT")
    print("-" * 40)

    print(
        classification_report(
            y_test,
            predictions,
            labels=[0, 1],
            target_names=["No Churn", "Churn"],
            zero_division=0,
        )
    )

    cm = confusion_matrix(
        y_test,
        predictions,
        labels=[0, 1],
    )

    print("CONFUSION MATRIX")
    print(cm)

    # --------------------------------------------------
    # 5. Save evaluation results
    # --------------------------------------------------

    print("\n[5/6] Saving evaluation results...")

    RESULTS_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    FIGURES_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    report = {
        "model": "Logistic Regression",
        "classification_threshold": threshold,
        "test_records": int(len(y_test)),
        "metrics": metrics,
        "confusion_matrix": cm.tolist(),
        "confusion_matrix_labels": [
            "No Churn",
            "Churn",
        ],
    }

    with METRICS_PATH.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            report,
            file,
            indent=4,
        )

    prediction_results = pd.DataFrame({
        "actual_churn": y_test.to_numpy(),
        "predicted_churn": predictions,
        "churn_probability": probabilities,
    })

    prediction_results.to_csv(
        PREDICTIONS_PATH,
        index=False,
    )

    print("PASS: Evaluation results saved.")

    # --------------------------------------------------
    # 6. Generate visualizations
    # --------------------------------------------------

    print("\n[6/6] Generating visualizations...")

    # Confusion matrix
    fig, ax = plt.subplots(figsize=(7, 5))

    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        cmap="Blues",
        xticklabels=["No Churn", "Churn"],
        yticklabels=["No Churn", "Churn"],
        ax=ax,
    )

    ax.set_title(
        "Customer Churn - Confusion Matrix"
    )
    ax.set_xlabel("Predicted Class")
    ax.set_ylabel("Actual Class")

    fig.tight_layout()

    fig.savefig(
        CONFUSION_FIGURE,
        dpi=300,
        bbox_inches="tight",
    )

    plt.close(fig)

    # ROC curve
    fpr, tpr, _ = roc_curve(
        y_test,
        probabilities,
    )

    fig, ax = plt.subplots(figsize=(7, 5))

    ax.plot(
        fpr,
        tpr,
        linewidth=2,
        label=f"Logistic Regression (AUC={metrics['roc_auc']:.4f})",
    )

    ax.plot(
        [0, 1],
        [0, 1],
        linestyle="--",
        color="gray",
        label="Random classifier",
    )

    ax.set_title("Customer Churn - ROC Curve")
    ax.set_xlabel("False Positive Rate")
    ax.set_ylabel("True Positive Rate")
    ax.legend()
    ax.grid(alpha=0.3)

    fig.tight_layout()

    fig.savefig(
        ROC_FIGURE,
        dpi=300,
        bbox_inches="tight",
    )

    plt.close(fig)

    assert METRICS_PATH.is_file()
    assert PREDICTIONS_PATH.is_file()
    assert CONFUSION_FIGURE.is_file()
    assert ROC_FIGURE.is_file()

    assert len(prediction_results) == 1409
    assert int(cm.sum()) == 1409

    print("PASS: Confusion matrix generated.")
    print("PASS: ROC curve generated.")

    print("\nSAVED OUTPUTS")
    print("-" * 40)

    for path in [
        METRICS_PATH,
        PREDICTIONS_PATH,
        CONFUSION_FIGURE,
        ROC_FIGURE,
    ]:
        print("[OK]", path.relative_to(PROJECT_ROOT))

    print("\n" + "=" * 60)
    print("MODEL EVALUATION COMPLETED SUCCESSFULLY")
    print("=" * 60)

    return report


if __name__ == "__main__":
    evaluate_model()
